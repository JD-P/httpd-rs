def write_site(source: Path) -> None:
    (source / "content/posts").mkdir(parents=True)
    (source / "content/private").mkdir(parents=True)
    (source / "layouts/_default").mkdir(parents=True)
    (source / "static/assets").mkdir(parents=True)
    (source / "hugo.toml").write_text(
        'baseURL = "http://deployment.test/"\n'
        'title = "Vapache Hugo Integration"\n'
        "disableKinds = ['taxonomy', 'term', 'sitemap', 'robotsTXT']\n"
    )
    (source / "content/_index.md").write_text("---\ntitle: Home\n---\nGenerated by Hugo for Vapache.\n")
    (source / "content/posts/hello.md").write_text(
        "---\ntitle: Hello deployment\n---\nA real generated static page.\n"
    )
    (source / "content/private/_index.md").write_text(
        "---\ntitle: Private deployment page\n---\nprivate-marker-4f3e\n"
    )
    (source / "layouts/_default/baseof.html").write_text(
        "<!doctype html><html><head><title>{{ .Title }}</title>"
        '<link rel="stylesheet" href="/assets/site.css"></head>'
        "<body><main>{{ block \"main\" . }}{{ end }}</main></body></html>\n"
    )
    (source / "layouts/_default/list.html").write_text(
        '{{ define "main" }}<h1>{{ .Title }}</h1>{{ .Content }}'
        '{{ range .Pages }}<a href="{{ .RelPermalink }}">{{ .Title }}</a>{{ end }}{{ end }}\n'
    )
    (source / "layouts/_default/single.html").write_text(
        '{{ define "main" }}<h1>{{ .Title }}</h1>{{ .Content }}{{ end }}\n'
    )
    (source / "layouts/404.html").write_text("<!doctype html><h1>hugo-custom-404</h1>\n")
    (source / "static/assets/site.css").write_text("body { color: #123456; }\n" * 200)
    (source / "static/assets/app.js").write_text("const vapache = 'hugo-static-marker';\n" * 200)
    (source / "static/assets/download.bin").write_bytes(bytes(range(256)) * 4096)


def build_hugo(context: CaseContext, source: Path) -> Path:
    validate_bind_source(source, context.run_dir)
    command(["docker", "pull", IMAGE], timeout=600, capture=False)
    if context.remove_images:
        context.add_cleanup(lambda: command(["docker", "image", "rm", IMAGE], check=False, timeout=120))
    command(
        [
            "docker",
            "run",
            "--rm",
            "--network",
            "none",
            "--read-only",
            "--cap-drop",
            "ALL",
            "--security-opt",
            "no-new-privileges:true",
            "--tmpfs",
            "/tmp:rw,noexec,nosuid,nodev,size=64m",
            "--tmpfs",
            f"/cache:rw,noexec,nosuid,nodev,size=256m,uid={os.getuid()},gid={os.getgid()}",
            "--user",
            f"{os.getuid()}:{os.getgid()}",
            "--mount",
            f"type=bind,src={source},dst=/project",
            "--workdir",
            "/project",
            IMAGE,
            "--minify",
        ],
        timeout=180,
        capture=False,
    )
    public = source / "public"
    if not (public / "index.html").exists():
        raise DeploymentError("Hugo did not generate public/index.html")
    make_readable_tree(public)
    return public


def run(context: CaseContext, variant: dict[str, str]) -> None:
    source = context.run_dir / "hugo"
    write_site(source)
    document_root = build_hugo(context, source)
    access_file = document_root / ".htaccess"
    access_file.write_text(
        "RewriteEngine On\n"
        "RewriteRule ^legacy$ /posts/hello/ [R=302,L]\n"
        "Header set X-Vapache-Deployment hugo\n"
    )
    os.chmod(access_file, 0o644)
    auth_file = context.run_dir / "htpasswd"
    auth_file.write_text("alice:{SHA}5en6G6MezRroT3XKqkdPOmY/BfQ=\n")
    os.chmod(auth_file, 0o644)
    cache_root = context.run_dir / "cache"
    cache_root.mkdir()
    os.chmod(cache_root, 0o777)
    port = free_port()

    access = ""
    if variant["access"] == "basic":
        access = f"""
<Directory "{document_root / 'private'}">
    AuthType Basic
    AuthName "Hugo private area"
    AuthUserFile "{auth_file}"
    Require valid-user
</Directory>
"""
    cache = ""
    if variant["cache"] == "disk":
        cache = f"""
CacheRoot "{cache_root}"
CacheEnable disk /assets/
CacheHeader On
CacheIgnoreNoLastMod On
CacheDefaultExpire 300
CacheMaxExpire 300
"""
    if variant["encoding"] == "brotli":
        compression = "AddOutputFilterByType BROTLI_COMPRESS text/html text/css application/javascript\nBrotliCompressionQuality 4"
        accepted_encoding = "br"
    else:
        compression = "AddOutputFilterByType DEFLATE text/html text/css application/javascript\nDeflateCompressionLevel 4"
        accepted_encoding = "gzip"

    extra = f"""
DirectoryIndex index.html
ErrorDocument 404 /404.html
<Directory "{document_root}">
    Options FollowSymLinks
    AllowOverride FileInfo
    Require all granted
</Directory>
{compression}
{cache}
{access}
"""
    config, pid_file = common_vapache_config(
        context.run_dir,
        port,
        document_root,
        capabilities=("AccessFiles",),
        extra=extra,
    )
    server = start_vapache(context, config, pid_file, port)

    require_response(port, "/", contains=b"Generated by Hugo for Vapache")
    require_response(port, "/posts/hello/", contains=b"real generated static page")
    headers, _ = require_response(port, "/assets/app.js")
    if headers.get("x-vapache-deployment") != "hugo":
        raise DeploymentError(".htaccess Header policy was not applied")
    status, redirect_headers, _ = request(port, "/legacy")
